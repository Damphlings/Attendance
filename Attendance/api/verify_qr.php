<?php
declare(strict_types=1);

require_once __DIR__ . '/../config/app.php';
require_once __DIR__ . '/../config/db.php';

header('Content-Type: application/json; charset=utf-8');
header('Cache-Control: no-store');

function verifyQrResponse(int $status, array $data): never
{
    http_response_code($status);
    echo json_encode($data, JSON_UNESCAPED_UNICODE);
    exit;
}

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    header('Allow: POST');
    verifyQrResponse(405, [
        'success' => false,
        'message' => 'Only POST requests are allowed.'
    ]);
}

if (empty($_SESSION['admin_id'])) {
    verifyQrResponse(401, [
        'success' => false,
        'message' => 'Please log in again.'
    ]);
}

// Accept either JSON or standard form data.
$contentType = $_SERVER['CONTENT_TYPE'] ?? '';

if (stripos($contentType, 'application/json') !== false) {
    $rawBody = file_get_contents('php://input');
    $input = json_decode($rawBody ?: '', true);

    if (!is_array($input)) {
        verifyQrResponse(400, [
            'success' => false,
            'message' => 'Invalid JSON request.'
        ]);
    }
} else {
    $input = $_POST;
}

$csrfToken = $_SERVER['HTTP_X_CSRF_TOKEN']
    ?? ($input['csrf_token'] ?? '');

$sessionToken = $_SESSION['csrf_token'] ?? '';

if (
    !is_string($csrfToken)
    || !is_string($sessionToken)
    || $csrfToken === ''
    || $sessionToken === ''
    || !hash_equals($sessionToken, $csrfToken)
) {
    verifyQrResponse(403, [
        'success' => false,
        'message' => 'Security token validation failed. Reload the page and try again.'
    ]);
}

$qrToken = $input['qr_token'] ?? '';

if (!is_string($qrToken)) {
    verifyQrResponse(400, [
        'success' => false,
        'message' => 'A valid QR token is required.'
    ]);
}

$qrToken = trim($qrToken);

if ($qrToken === '' || strlen($qrToken) > 512) {
    verifyQrResponse(400, [
        'success' => false,
        'message' => 'The QR code is empty or invalid.'
    ]);
}

// QR tokens generated by generate_qr_token() are 64 hexadecimal characters.
if (!preg_match('/^[a-fA-F0-9]{64}$/', $qrToken)) {
    verifyQrResponse(400, [
        'success' => false,
        'message' => 'The QR code format is invalid.'
    ]);
}

$tokenHash = hash('sha256', $qrToken);

try {
    $stmt = $pdo->prepare(
        'SELECT id, member_code, full_name, position, email, status
         FROM members
         WHERE qr_token_hash = :token_hash
         LIMIT 1'
    );

    $stmt->execute([
        ':token_hash' => $tokenHash
    ]);

    $member = $stmt->fetch();

    if (!$member) {
        verifyQrResponse(404, [
            'success' => false,
            'message' => 'QR code not recognized. Please check the member QR code.'
        ]);
    }

    if (strcasecmp((string) $member['status'], 'Active') !== 0) {
        verifyQrResponse(403, [
            'success' => false,
            'message' => 'This member is inactive and cannot be checked in.'
        ]);
    }

    verifyQrResponse(200, [
        'success' => true,
        'message' => 'Member verified successfully.',
        'member' => [
            'id' => (int) $member['id'],
            'member_code' => $member['member_code'],
            'full_name' => $member['full_name'],
            'position' => $member['position'],
            'email' => $member['email'],
            'status' => $member['status']
        ]
    ]);

} catch (PDOException $e) {
    error_log('QR verification error: ' . $e->getMessage());

    verifyQrResponse(500, [
        'success' => false,
        'message' => 'Unable to verify the QR code right now.'
    ]);
}